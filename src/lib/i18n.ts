export const dictionaries: Record<string, Dict> = { fa, en };

export type TranslateFn = (key: string, vars?: Record<string, string | number>) => string;

export function makeT(lang: string): TranslateFn {
  const dict = dictionaries[lang] ?? fa;
  return (key, vars) => {
    let s = dict[key] ?? fa[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
    }
    return s;
  };
}

export function interpolate(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s;
  let out = s;
  for (const [k, v] of Object.entries(vars)) out = out.replaceAll(`{${k}}`, String(v));
  return out;
}
